import {
  Link,
  Links,
  Meta,
  Outlet,
  Scripts,
  ScrollRestoration,
  isRouteErrorResponse,
  useFetchers,
  useRouteLoaderData,
} from "react-router";
import type { Route } from "./+types/root";
import { useLocale, useT } from "./i18n/useT";
import { BRAND, BRAND_ICONS } from "./shared/brand";
import { DEFAULT_COUNTRY } from "./shared/countries";
import { DEFAULT_LOCALE, dirFor, localeFromPathname } from "./shared/locales";
import type { ClientUser } from "./shared/schemas/auth";
import { DEFAULT_THEME, themeSchema } from "./shared/schemas/theme";
import { skipSearchOnlyRevalidation } from "./utils/revalidate";
import { getTheme } from "./utils/theme.server";
import "./app.css";

export const shouldRevalidate = skipSearchOnlyRevalidation;

/** Site icons and web manifest (generated by `npm run icons`, SPEC §14). */
export const links: Route.LinksFunction = () => [
  { rel: "icon", href: BRAND_ICONS.ico, sizes: "48x48" },
  { rel: "icon", href: BRAND_ICONS.svg, type: "image/svg+xml" },
  { rel: "apple-touch-icon", href: BRAND_ICONS.appleTouch },
  { rel: "manifest", href: BRAND_ICONS.manifest },
];

export async function loader({ request, context }: Route.LoaderArgs) {
  const locale = localeFromPathname(new URL(request.url).pathname);
  const theme = await getTheme(request);
  // Serialized into the HTML: explicit fields only (no email, phone or tokens).
  const session = context.session;
  const user: ClientUser | null = session
    ? { id: session.user.id, name: session.user.name, role: session.user.role }
    : null;
  return { locale, theme, user };
}

/** Theme being submitted by the toggle, so the page switches before the round-trip ends. */
function usePendingTheme() {
  const fetcher = useFetchers().find((f) => f.formAction === "/theme" && f.formData);
  const parsed = themeSchema.safeParse(fetcher?.formData?.get("theme"));
  return parsed.success ? parsed.data : undefined;
}

export function Layout({ children }: { children: React.ReactNode }) {
  const data = useRouteLoaderData<typeof loader>("root");
  const locale = data?.locale ?? DEFAULT_LOCALE;
  const theme = usePendingTheme() ?? data?.theme ?? DEFAULT_THEME;

  return (
    <html lang={locale} dir={dirFor(locale)} className={theme}>
      <head>
        <meta charSet="utf-8" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <meta name="theme-color" content={BRAND.themeColor[theme]} />
        <Meta />
        <Links />
      </head>
      <body
        className={`min-h-dvh bg-background text-foreground antialiased ${
          locale === "ar" ? "font-arabic" : "font-latin"
        }`}
      >
        {children}
        <ScrollRestoration />
        <Scripts />
      </body>
    </html>
  );
}

export default function App() {
  return <Outlet />;
}

export function ErrorBoundary({ error }: Route.ErrorBoundaryProps) {
  const t = useT();
  const locale = useLocale();
  const notFound = isRouteErrorResponse(error) && error.status === 404;
  const title = t(notFound ? "errors.notFoundTitle" : "errors.genericTitle");

  if (!notFound && import.meta.env.DEV) console.error(error);

  return (
    <main className="mx-auto flex min-h-dvh max-w-xl flex-col items-center justify-center gap-4 p-6 text-center">
      <title>{`${title} | ${t("app.name")}`}</title>
      <h1 className="text-2xl font-bold">{title}</h1>
      <p className="text-muted">{t(notFound ? "errors.notFoundBody" : "errors.genericBody")}</p>
      <Link
        to={`/${locale}/${DEFAULT_COUNTRY}/map`}
        className="rounded-lg bg-primary px-4 py-2 font-semibold text-on-primary hover:bg-primary-hover"
      >
        {t("errors.backHome")}
      </Link>
    </main>
  );
}
